#ifndef __CROSSLINK_EXPR_H__
#define __CROSSLINK_EXPR_H__

#include <stdint.h>

/*  Грамматика значения в позиции действия:

        <value> ::= ( '@' | <num> ) { <op> <num> }
        <op>    ::= '*' | '/' | '+' | '-'
        <num>   ::= ['-'] цифры [ '.' цифры ]

    '@' - значение события. Операции применяются СЛЕВА НАПРАВО, без приоритета
    умножения: '@+10*2' это (v+10)*2, а не v+20. Для конфигурационного файла
    предсказуемость важнее школьной привычки, и типовая запись 'масштаб, потом
    смещение' - '@*3.8+1000' - в обоих прочтениях совпадает.

    Экспоненциальная запись не поддерживается: '1e3' - ошибка разбора.
    Разделитель дробной части только точка - запятая занята под разделитель
    правил crosslink.                                                        */

#define XL_MAX_OPS      4

typedef enum {
    XL_OP_NONE = 0,
    XL_OP_MUL,
    XL_OP_DIV,
    XL_OP_ADD,
    XL_OP_SUB
} xl_op_kind_t;

typedef struct {
    uint8_t         passthrough;            /* 1 - выражение начинается с '@' */
    float           constant;               /* при passthrough == 0           */
    uint8_t         count;                  /* сколько операций в цепочке     */
    xl_op_kind_t    op      [ XL_MAX_OPS ];
    float           operand [ XL_MAX_OPS ];
} xl_expr_t;

/* Разбор выражения. 0 - успех, отрицательное - ошибка:
     -1 пустая строка
     -2 неожиданный символ
     -3 деление на ноль (ловится на разборе - константа известна заранее)
     -4 цепочка длиннее XL_MAX_OPS                                           */
int xl_expr_parse(const char *src, xl_expr_t *out);

/* Вычислить. in - значение события; при passthrough == 0 игнорируется. */
float xl_expr_eval(const xl_expr_t *e, float in);

/* Выражение это голый '@' без операций - значение переносится как есть. */
int xl_expr_is_passthrough(const xl_expr_t *e);

/* Записать результат в буфер так, чтобы его принял разбор параметров команды.
   Всегда целое, округление к ближайшему, половина от нуля: команда с
   PARAMT_int отвергает дробное значение, а целое принимают и int, и float.
   Возвращает buf.                                                          */
char * xl_expr_format(float value, char *buf, int size);

#endif // __CROSSLINK_EXPR_H__
