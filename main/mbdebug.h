#ifndef __MBDEBUG_H__
#define __MBDEBUG_H__

#include <esp_log.h>

// ---------------------------------------------------------------------------
// ------------------------------- DEFINITIONS -------------------------------
// -----|-------------------|-------------------------------------------------

#define E           ESP_LOG_ERROR
#define W           ESP_LOG_WARN
#define I           ESP_LOG_INFO
#define D           ESP_LOG_DEBUG
#define V           ESP_LOG_VERBOSE

// #define JTAG_USED


// ---------------------------------------------------------------------------
// -------------------------------- FUNCTIONS --------------------------------
// -----------------|---------------------------(|------------------|---------

void mblog_init();
void mblog(esp_log_level_t priority, const char *msg,...);
char * _getAvailableBuff(int * avail);

/** Сбросить накопленный лог на карту (fflush + fsync). Только в этот момент
 *  трогаются метаданные тома - между сбросами файл просто держится открытым. */
void mblog_flush(void);

/** Дописать и закрыть лог. Обязательно перед перезагрузкой-размонтированием:
 *  файл держится открытым, поэтому иначе хвост лога и размер в каталоге на
 *  карту не попадут. Мьютекс берётся с таймаутом - ребут не должен зависнуть. */
void mblog_close(void);

#endif // #define __MBDEBUG_H__
